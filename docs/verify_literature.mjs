import fs from 'node:fs';
import assert from 'node:assert/strict';
import {condenserHeatRate,SteamSimulation} from './web/steam-simulation.js';
import {compareHeat} from './web/heat-comparison.js';
const audit=JSON.parse(fs.readFileSync('literature-audit.json'));
const data=JSON.parse(fs.readFileSync('simulation-data.json'));
const v=audit.independent_results,k=data.defaults,checks=[];
const test=(name,pass,detail)=>{assert.ok(pass,name);checks.push({name,pass,detail});};
const q=condenserHeatRate(k.condenser_UA_W_K,k.airflow_m3_s,v.condensing_C,k.ambient_C);
test('Air warming agrees with independent Python reference',Math.abs(q-v.corrected_cooling_W)<1e-8,q);
test('Condenser cannot reach both infinite-UA and infinite-air bounds',q<v.old_cooling_W&&q>0);
test('Fans stopped have no forced cooling',condenserHeatRate(2000,0,100,20)===0);
test('Zero conductance has no heat transfer',condenserHeatRate(0,1,100,20)===0);
test('Equal temperatures have no heat transfer',condenserHeatRate(2000,1,20,20)===0);
test('Air can warm a colder lumped body',condenserHeatRate(2000,1,10,20)<0);
test('Large airflow approaches UA deltaT bound',Math.abs(condenserHeatRate(2000,1e8,100,20)-160000)<.01);
const sim=new SteamSimulation(data);sim.run=true;sim.phase=2;
sim.c.E=sim.equilibrium(sim.c.M,sim.c.V,sim.c.C,sim.c.air,v.condensing_C).E;
sim.initialEnergy=sim.energy();
const before=sim.state(sim.c);const current=sim.step(.05);
test('Time integration uses finite-air-warming law',Math.abs(current.cooling-condenserHeatRate(k.condenser_UA_W_K,k.airflow_m3_s,before.T,k.ambient_C))<1e-8,current.cooling);
test('Time integration keeps its thermal balance after correction',Math.abs(current.energy_residual_J)<.001,current.energy_residual_J);
const row=compareHeat(data)[0];
test('Audit reproduces current comparison steam flow',Math.abs(row.steam_kg_h-v.comparison_steam_kg_h)<1e-8,row.steam_kg_h);
test('Known missing subcooling is quantified, not concealed',v.missing_subcooler_W>3400&&v.missing_subcooler_W<3600,v.missing_subcooler_W);
test('Current comparison condenser duty is independently reproduced',Math.abs(row.condenser_kW*1000-v.comparison_condenser_W)<1e-8,row.condenser_kW);
test('Finite stroke expansion ends above exhaust pressure',v.finite_end_pressure_Pa>120000,v.finite_end_pressure_Pa);
test('Finite expansion work is below full-expansion work',v.finite_expansion_work_J_kg<v.isentropic_drop_J_kg);
test('Wheel speed reference is physically consistent',v.wheel_rpm_at_70>660&&v.wheel_rpm_at_70<665,v.wheel_rpm_at_70);
fs.writeFileSync('literature-checks.json',JSON.stringify({status:'passed',checks,scope:'Independent reference values and condenser implementation. Open findings in literature-audit.json remain unresolved; this does not validate real components.'},null,2)+'\n');
console.log(JSON.stringify({status:'passed',checks:checks.length,cooling_kW:q/1000,open_findings:audit.findings.filter(f=>!f.status.startsWith('Исправлено')).length}));
